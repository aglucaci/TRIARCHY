#!/usr/bin/env bash
set -Eeuo pipefail

ENV_PREFIX=""
INSTALL_FORMULAS=false

usage() {
    cat <<'EOF'
Usage: scripts/configure_conda_native_tools.sh --env-prefix DIR [--install]

Expose native Apple-silicon Homebrew bioinformatics tools whenever the selected
Conda environment is active. The environment's original PATH is restored on
deactivation.

Options:
  --env-prefix DIR   Conda environment prefix to configure
  --install          Run `brew install bowtie2 bracken` first
  -h, --help         Show this help
EOF
}

die() {
    printf 'ERROR: %s\n' "$*" >&2
    exit 1
}

while (($#)); do
    case "$1" in
        --env-prefix)
            (($# >= 2)) || die "--env-prefix requires a directory"
            ENV_PREFIX="$2"
            shift 2
            ;;
        --install)
            INSTALL_FORMULAS=true
            shift
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            die "unknown option: $1"
            ;;
    esac
done

[[ -n "${ENV_PREFIX}" ]] || die "--env-prefix is required"
[[ -x "${ENV_PREFIX}/bin/python3" ]] ||
    die "not a Conda environment: ${ENV_PREFIX}"
[[ "$(uname -s)" == "Darwin" && "$(uname -m)" == "arm64" ]] ||
    die "native Homebrew integration is only required on Apple-silicon macOS"
command -v brew >/dev/null 2>&1 ||
    die "Homebrew is required: https://brew.sh"

if [[ "${INSTALL_FORMULAS}" == true ]]; then
    brew install bowtie2 bracken
fi

native_paths=()
for formula in bowtie2 bracken kraken2; do
    formula_prefix="$(brew --prefix "${formula}" 2>/dev/null || true)"
    [[ -d "${formula_prefix}/bin" ]] ||
        die "Homebrew formula ${formula} is missing; run: brew install bowtie2 bracken"
    native_paths+=("${formula_prefix}/bin")
done
native_path="$(IFS=:; printf '%s' "${native_paths[*]}")"

activate_dir="${ENV_PREFIX}/etc/conda/activate.d"
deactivate_dir="${ENV_PREFIX}/etc/conda/deactivate.d"
mkdir -p "${activate_dir}" "${deactivate_dir}"

activate_hook="${activate_dir}/triarchy-native-tools.sh"
deactivate_hook="${deactivate_dir}/triarchy-native-tools.sh"

{
    printf '%s\n' '# Generated by TRIARCHY; native Apple-silicon tool shims.'
    printf '%s\n' 'if [[ -z "${TRIARCHY_NATIVE_TOOLS_ACTIVE:-}" ]]; then'
    printf '%s\n' '    export TRIARCHY_PATH_BEFORE_NATIVE_TOOLS="${PATH}"'
    printf '    export PATH="%s:${PATH}"\n' "${native_path}"
    printf '%s\n' '    export TRIARCHY_NATIVE_TOOLS_ACTIVE=1'
    printf '%s\n' 'fi'
} >"${activate_hook}"

{
    printf '%s\n' '# Generated by TRIARCHY; restore PATH on Conda deactivation.'
    printf '%s\n' 'if [[ -n "${TRIARCHY_PATH_BEFORE_NATIVE_TOOLS:-}" ]]; then'
    printf '%s\n' '    export PATH="${TRIARCHY_PATH_BEFORE_NATIVE_TOOLS}"'
    printf '%s\n' 'fi'
    printf '%s\n' 'unset TRIARCHY_PATH_BEFORE_NATIVE_TOOLS'
    printf '%s\n' 'unset TRIARCHY_NATIVE_TOOLS_ACTIVE'
} >"${deactivate_hook}"

printf 'Configured native tools for Conda environment: %s\n' "${ENV_PREFIX}"
printf 'Native PATH prefix: %s\n' "${native_path}"
printf 'Reactivate the environment to apply it: conda activate %s\n' \
    "${ENV_PREFIX}"
